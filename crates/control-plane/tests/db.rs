/// A pool whose connections all use a private schema, plus the schema name.
struct TestDb {
    pool: PgPool,
    schema: String,
    admin: PgPool,
}

impl TestDb {
    async fn drop_schema(self) {
        self.pool.close().await;
        // Schema names are generated by this test file (uuid-based), never user input.
        let _ = sqlx::query(AssertSqlSafe(format!(
            "DROP SCHEMA IF EXISTS {} CASCADE",
            self.schema
        )))
        .execute(&self.admin)
        .await;
        self.admin.close().await;
    }
}

/// `None` (after printing "skipping") when `DATABASE_URL` is unset.
async fn setup() -> Option<TestDb> {
    let Ok(url) = std::env::var("DATABASE_URL") else {
        eprintln!("skipping: DATABASE_URL not set");
        return None;
    };
    let schema = format!("cp_test_{}", Uuid::new_v4().simple());
    let admin = PgPoolOptions::new()
        .max_connections(1)
        .connect(&url)
        .await
        .unwrap();
    sqlx::query(AssertSqlSafe(format!("CREATE SCHEMA {schema}")))
        .execute(&admin)
        .await
        .unwrap();
    let opts = PgConnectOptions::from_str(&url)
        .unwrap()
        .options([("search_path", schema.as_str())]);
    let pool = PgPoolOptions::new()
        .max_connections(4)
        .connect_with(opts)
        .await
        .unwrap();
    db::migrate(&pool).await.unwrap();
    Some(TestDb {
        pool,
        schema,
        admin,
    })
}

async fn call(app: Router, req: Request<Body>) -> (StatusCode, Vec<u8>) {
    let res = app.oneshot(req).await.unwrap();
    let status = res.status();
    let bytes = res.into_body().collect().await.unwrap().to_bytes().to_vec();
    (status, bytes)
}

fn json<T: DeserializeOwned>(bytes: &[u8]) -> T {
    serde_json::from_slice(bytes).unwrap_or_else(|e| {
        panic!(
            "invalid JSON body {:?}: {e}",
            String::from_utf8_lossy(bytes)
        )
    })
}

fn req_json(method: &str, uri: &str, body: &impl serde::Serialize) -> Request<Body> {
    Request::builder()
        .method(method)
        .uri(uri)
        .header(header::CONTENT_TYPE, "application/json")
        .body(Body::from(serde_json::to_vec(body).unwrap()))
        .unwrap()
}

fn get(uri: &str) -> Request<Body> {
    Request::get(uri).body(Body::empty()).unwrap()
}

fn pdf_pipeline(uid: &str, project_id: Option<&str>) -> PipelineDefinition {
    PipelineDefinition {
        uid: uid.into(),
        name: format!("{uid} name"),
        description: Some("desc".into()),
        version: 1,
        trigger: Some(PipelineTrigger {
            content_types: vec!["application/pdf".into()],
            filename_pattern: None,
            index_pattern: Some(format!("{uid}-idx")),
        }),
        steps: vec![
            StepDefinition::new("extract", "pdf_extractor"),
            StepDefinition::new("index", "meili_indexer"),
        ],
        builtin: false,
        project_id: project_id.map(str::to_owned),
    }
}

