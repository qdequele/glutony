//! in its own freshly created schema (via `search_path`) and drops it afterwards.
//!
//! ```sh
//! DATABASE_URL=postgres://postgres:dev@localhost:55432/postgres \
//!   cargo test -p meili-ingest-control-plane --test db
//! ```

